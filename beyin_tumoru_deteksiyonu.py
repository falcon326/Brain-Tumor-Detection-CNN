import tensorflow as tf
from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import Conv2D, MaxPooling2D, Flatten, Dense, Dropout
from tensorflow.keras.preprocessing.image import ImageDataGenerator
from sklearn.model_selection import train_test_split
import numpy as np
import os
import matplotlib.pyplot as plt

from google.colab import drive
drive.mount('/content/drive')

#veri setini hazırlama

# Veri setinin yolu
data_dir = "/content/drive/MyDrive/Colab_Notebooks/brain_tumor_detection/image-processing"  # "yes" ve "no" klasörleri burada olmalı

# Görüntüleri ve etiketleri yükle
images = []
labels = []

for label, class_name in enumerate(["no", "yes"]):
    class_dir = os.path.join(data_dir, class_name)
    for img_name in os.listdir(class_dir):
        img_path = os.path.join(class_dir, img_name)
        img = tf.keras.preprocessing.image.load_img(img_path, target_size=(150, 150))
        img_array = tf.keras.preprocessing.image.img_to_array(img)
        images.append(img_array)
        labels.append(label)

# Listeleri numpy array'ine dönüştür
images = np.array(images)
labels = np.array(labels)

# Veri setini eğitim ve test olarak böl (örneğin, %80 eğitim, %20 test)
X_train, X_test, y_train, y_test = train_test_split(images, labels, test_size=0.2, random_state=42)

# Normalizasyon (0-255 arası değerleri 0-1 arasına ölçekle)
X_train = X_train / 255.0
X_test = X_test / 255.0

#CNN modeli pluşturma

model = Sequential()

# 1. konvolüsyonel Katman + maxpooling
model.add(Conv2D(32, (3, 3), activation='relu', input_shape=(150, 150, 3)))
model.add(MaxPooling2D(pool_size=(2, 2)))

# 2. konvolüsyonel Katman + maxpooling
model.add(Conv2D(64, (3, 3), activation='relu'))
model.add(MaxPooling2D(pool_size=(2, 2)))

# 3. konvolüsyonel Katman + maxpooling
model.add(Conv2D(128, (3, 3), activation='relu'))
model.add(MaxPooling2D(pool_size=(2, 2)))

# Düzleştirme (flatten) Katman
model.add(Flatten())

# Tam Bağlantılı (dense) Katman + dropout
model.add(Dense(512, activation='relu'))
model.add(Dropout(0.5))

# Çıkış Katmanı
model.add(Dense(1, activation='sigmoid'))

# Modeli Derle
model.compile(optimizer='adam', loss='binary_crossentropy', metrics=['accuracy'])

# Model Özeti
model.summary()

#modeli eğit

history = model.fit(
    X_train, y_train,
    epochs=15,
    batch_size=32,
    validation_data=(X_test, y_test)
)

#modeli değerlendir

# Eğitim ve doğrulama kaybını çiz
plt.plot(history.history['loss'], label='Eğitim Kaybı')
plt.plot(history.history['val_loss'], label='Doğrulama Kaybı')
plt.xlabel('Epoch')
plt.ylabel('Kayıp')
plt.legend()
plt.show()

# Eğitim ve doğrulama doğruluğunu çiz
plt.plot(history.history['accuracy'], label='Eğitim Doğruluğu')
plt.plot(history.history['val_accuracy'], label='Doğrulama Doğruluğu')
plt.xlabel('Epoch')
plt.ylabel('Doğruluk')
plt.legend()
plt.show()

# Test veri seti üzerinde modeli değerlendir (Test)
test_loss, test_acc = model.evaluate(X_test, y_test)
print(f"Test Doğruluğu: {test_acc:.2f}")

